import { PreparePlan } from "@/components/prepare-plan";
import { buttonClass, secondaryButtonClass, when } from "@/components/ui";
import type { CustomerQuestion, LaunchStrategy } from "@/integrations/ai/types";
import type { LaunchStatus } from "@/types/launch";
import { approveLaunchPlanAction, requestPlanChangesAction } from "@/app/(founder)/dashboard/actions";

type Plan = {
  strategy: { version: number; status: string; strategy: LaunchStrategy; customer_questions: CustomerQuestion[]; approved_at: string | null; founder_notes: string | null } | null;
  runbook: {
    title: string; duration_minutes: number; opening_hook: string | null; problem_statement: string | null;
    demo_plan: Array<{ step: string; minutes: number; script: string }>; cta_script: string | null; closing_script: string | null;
  } | null;
  provenance: { source: string; model: string; prompt_version: string; completed_at: string | null } | null;
  lastRun: { status: string; error_message: string | null } | null;
};

const BEFORE_PLAN: LaunchStatus[] = ["DRAFT", "INTAKE_IN_PROGRESS", "SUBMITTED", "QUALIFICATION_REVIEW", "CHANGES_REQUIRED", "QUALIFIED", "LAUNCH_TYPE_SELECTED"];

/** §59/§82 launch plan: generation progress, the AI draft with provenance, and founder approval. */
export function LaunchPlan({ launchId, status, plan }: { launchId: string; status: LaunchStatus; plan: Plan }) {
  if (BEFORE_PLAN.includes(status)) return <p className="text-slate-600">Your launch strategy and run-of-show are prepared right after payment.</p>;
  if (status === "PREPARATION") {
    const lastError = plan.lastRun?.status === "failed" ? plan.lastRun.error_message ?? "The last attempt failed." : null;
    return <PreparePlan launchId={launchId} lastError={lastError} />;
  }
  const { strategy: s, runbook: r, provenance: p } = plan;
  if (!s || !r) return <p className="text-slate-600">No launch plan is on file for this launch.</p>;
  const st = s.strategy;
  const awaiting = status === "AWAITING_FOUNDER_APPROVAL" && s.status === "draft";
  const mocked = p?.source === "mock";

  return (
    <div className="space-y-6">
      <div className={`rounded-lg px-4 py-3 text-sm ${mocked ? "border border-amber-300 bg-amber-50 text-amber-900" : "border border-slate-200 bg-slate-50 text-slate-700"}`}>
        {mocked
          ? "Placeholder plan: AI isn't connected yet, so this is sample text, not a real analysis."
          : `Version ${s.version} · ${s.status === "approved" ? `approved ${when(s.approved_at)}` : "AI draft, not used until you approve it"}`}
        {p && <span className="block text-xs text-slate-500">Generated by {p.model} ({p.prompt_version}) {when(p.completed_at)}</span>}
      </div>

      <section className="space-y-2">
        <h3 className="font-semibold">Strategy</h3>
        <dl className="grid gap-3 text-sm sm:grid-cols-2">
          <div><dt className="text-slate-500">Objective</dt><dd>{st.launchObjective}</dd></div>
          <div><dt className="text-slate-500">Audience</dt><dd>{st.primaryAudience}</dd></div>
          <div><dt className="text-slate-500">Problem</dt><dd>{st.positioning.problem}</dd></div>
          <div><dt className="text-slate-500">Promise</dt><dd>{st.positioning.promise}</dd></div>
          <div><dt className="text-slate-500">Proof</dt><dd>{st.positioning.proof}</dd></div>
          <div><dt className="text-slate-500">Opening hook</dt><dd>{st.recommendedHook}</dd></div>
          <div className="sm:col-span-2"><dt className="text-slate-500">Call to action</dt><dd><span className="font-medium">{st.primaryCta.text}</span> <span className="text-slate-500">({st.primaryCta.rationale})</span></dd></div>
        </dl>
        {st.risks.length > 0 && (
          <div className="text-sm"><p className="text-slate-500">Risks and claims to check</p><ul className="list-disc pl-5">{st.risks.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
        )}
      </section>

      <section className="space-y-2">
        <h3 className="font-semibold">Run-of-show: {r.title} ({r.duration_minutes} min)</h3>
        {r.opening_hook && <p className="text-sm"><span className="text-slate-500">Open with: </span>{r.opening_hook}</p>}
        {r.problem_statement && <p className="text-sm"><span className="text-slate-500">Problem: </span>{r.problem_statement}</p>}
        <ol className="space-y-2 text-sm">
          {r.demo_plan.map((step, i) => (
            <li key={i} className="rounded-md border border-slate-100 p-3">
              <p className="font-medium">{i + 1}. {step.step} <span className="font-normal text-slate-500">· {step.minutes} min</span></p>
              <p className="mt-1 whitespace-pre-line text-slate-600">{step.script}</p>
            </li>
          ))}
        </ol>
        {r.cta_script && <p className="text-sm"><span className="text-slate-500">Call to action script: </span>{r.cta_script}</p>}
        {r.closing_script && <p className="text-sm"><span className="text-slate-500">Close: </span>{r.closing_script}</p>}
      </section>

      <section className="space-y-2">
        <h3 className="font-semibold">Questions customers will probably ask</h3>
        <ul className="space-y-2 text-sm">
          {s.customer_questions.map((q, i) => (
            <li key={i}><p className="font-medium">{q.question}</p><p className="text-slate-500">{q.whyItMatters}</p></li>
          ))}
        </ul>
      </section>

      {awaiting && (
        <div className="grid gap-4 border-t border-slate-100 pt-4 md:grid-cols-2">
          <form action={approveLaunchPlanAction} className="space-y-2">
            <input type="hidden" name="launchId" value={launchId} />
            <input type="hidden" name="version" value={s.version} />
            <p className="text-sm text-slate-600">Approving locks this version as your plan and moves you on to scheduling.</p>
            <button className={buttonClass}>Approve plan</button>
          </form>
          <form action={requestPlanChangesAction} className="space-y-2">
            <input type="hidden" name="launchId" value={launchId} />
            <label className="block text-sm">
              <span className="font-medium text-slate-800">Ask for changes</span>
              <textarea name="notes" required minLength={5} maxLength={2000} rows={3} className="mt-1 w-full rounded-md border border-slate-300 px-3 py-2 text-sm" placeholder="For example: focus on agencies, and make the call to action a free trial." />
            </label>
            <button className={secondaryButtonClass}>Rebuild the plan</button>
          </form>
        </div>
      )}
    </div>
  );
}
