-- Checkout orders: one row per Stripe Checkout Session. Created as 'pending' when checkout opens,
-- flipped to 'paid' only by the verified Stripe webhook. Founders can read their org's orders;
-- only server code (service role) writes them.
--
-- Down migration (reversible; table holds no data other tables depend on):
--   drop table if exists public.launch_orders;

create table public.launch_orders (
  id uuid primary key,                          -- generated by the app so it can go into Stripe metadata
  organization_id uuid not null,
  launch_id uuid not null,
  stripe_session_id text not null unique,
  status text not null default 'pending' check (status in ('pending','paid')),
  amount integer not null check (amount >= 0),  -- minor units, copied from the launch price snapshot
  currency text not null check (currency ~ '^[a-z]{3}$'),
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  updated_at timestamptz not null default now(),
  check ((status = 'paid') = (paid_at is not null)),
  foreign key (launch_id, organization_id) references public.launches(id, organization_id) on delete restrict
);
create index launch_orders_launch_idx on public.launch_orders (launch_id);
create trigger launch_orders_updated_at before update on public.launch_orders
  for each row execute function public.set_updated_at();
alter table public.launch_orders enable row level security;
create policy launch_orders_select on public.launch_orders for select to authenticated
  using (public.is_org_member(organization_id));
revoke insert, update, delete on public.launch_orders from anon, authenticated;
